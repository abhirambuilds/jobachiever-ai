@pytest.mark.asyncio
async def test_streaming_generation(gemini_settings, mock_gemini_client):
    async def mock_stream():
        chunks = ["Google", " ", "Gemini", " ", "Response"]
        for c in chunks:
            chunk_mock = MagicMock()
            chunk_mock.text = c
            yield chunk_mock

    mock_gemini_client.aio.models.generate_content_stream.return_value = mock_stream()

    provider = GeminiProvider(gemini_settings, client=mock_gemini_client)
    req = AIGenerationRequest(provider="GEMINI", prompt="Stream please")

    collected = []
    async for token in provider.stream_text(req):
        collected.append(token)

    assert "".join(collected) == "Google Gemini Response"
