@pytest.mark.asyncio
async def test_valid_text_generation(gemini_settings, mock_gemini_client):
    mock_gemini_client.aio.models.generate_content.return_value = make_mock_gemini_response(
        text="Targeted professional summary from Gemini 2.0 Flash",
        finish_reason="STOP",
        prompt_tokens=20,
        candidates_tokens=45
    )

    provider = GeminiProvider(gemini_settings, client=mock_gemini_client)
    req = AIGenerationRequest(
        provider="GEMINI",
        prompt="Draft an executive summary",
        system_prompt="You are a senior tech recruiter."
    )

    response = await provider.generate_text(req)

    assert response.provider == "GEMINI"
    assert response.model == "gemini-2.0-flash"
    assert response.content == "Targeted professional summary from Gemini 2.0 Flash"
    assert response.usage is not None
    assert response.usage.input_tokens == 20
    assert response.usage.output_tokens == 45
    assert response.usage.total_tokens == 65
    assert response.finish_reason == "STOP"
    assert response.processing_time_ms > 0


